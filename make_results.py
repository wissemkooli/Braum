#!/usr/bin/env python3
"""Regenerate docs/RESULTS.md from actual runs.

Every table in the technical report comes from here, so the numbers in the
write-up cannot drift away from the code. Run it after any change:

    python3 make_results.py
"""

from __future__ import annotations

import contextlib
import io
import os
import re
import subprocess
import sys
from datetime import date

import sentinel_cli

MAIN = ["scenarios/public", "scenarios/hard_negatives", "scenarios/extended"]
PROBES = ["scenarios/known_failures"]

SECTIONS = [
    ("Full scenario library, SENTINEL defense", ["suite", "--scenarios", *MAIN]),
    ("Pass/fail by attack family", ["families", "--scenarios", *MAIN]),
    ("SENTINEL against every baseline", ["compare", "--scenarios", *MAIN]),
    ("Ablation", ["ablate", "--scenarios", *MAIN, "--verbose-ablation"]),
    ("Risk-score calibration", ["calibrate", "--scenarios", *MAIN]),
    ("Adaptive probes — scenarios the defense does NOT stop",
     ["suite", "--scenarios", *PROBES]),
]

STRIP_ANSI = re.compile(r"\033\[[0-9;]*m")


def capture(argv):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        sentinel_cli.main(argv)
    return STRIP_ANSI.sub("", buf.getvalue()).strip("\n")


def main() -> int:
    parts = [
        "# Results",
        "",
        "Generated by `python3 make_results.py` — do not edit by hand.",
        "",
        f"- date: {date.today().isoformat()}",
        f"- python: {sys.version.split()[0]}",
        "- agent: `susceptible` (follows instructions it finds in observed content)",
        "- escalations: answered per scenario (`deny` unless the scenario places a "
        "human on shift)",
        "",
    ]
    for title, argv in SECTIONS:
        try:
            body = capture(argv)
        except SystemExit:
            body = "(command exited non-zero; see above)"
        parts += [f"## {title}", "", "```", body, "```", ""]

    os.makedirs("docs", exist_ok=True)
    with open("docs/RESULTS.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))
    print("wrote docs/RESULTS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
